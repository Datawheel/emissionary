/**
 * Generates data/SOURCES.md — the human-readable methodology appendix
 * (spec §4.3.3) — deterministically from the source registry and items.
 *
 * Usage: npx tsx scripts/generate-sources-md.ts
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadItems, loadSources } from '../src/lib/data';
import { DIESEL_KGCO2_PER_L, FUEL_GCO2_PER_KWH_THERMAL, PETROL_KGCO2_PER_L } from '../src/lib/constants';
import type { Item } from '../src/lib/types';

function itemValue(i: Item): string {
  switch (i.energy_model) {
    case 'power':
      return `${i.power_watts} W (${i.carrier})`;
    case 'per_event':
      return `${i.kwh_per_event} kWh/${i.event_noun?.en ?? 'event'}`;
    case 'task':
      return `${i.task_kwh_useful} kWh useful/L ÷ ${Math.round((i.efficiency ?? 0) * 100)}% (${i.carrier})`;
    case 'per_km':
      if (i.uses_country_car_default) return 'country average gCO₂/km';
      if (i.kwh_per_km != null) return `${i.kwh_per_km} kWh/km`;
      if (i.l_per_100km != null) return `${i.l_per_100km} L/100km (${i.carrier})`;
      return `${i.gco2_per_km} gCO₂/km`;
  }
}

export function generateSourcesMd(): string {
  const sources = loadSources();
  const items = loadItems();
  const lines: string[] = [];
  lines.push('# Emissionary — data sources and methodology');
  lines.push('');
  lines.push('_Generated by `scripts/generate-sources-md.ts` — do not edit by hand._');
  lines.push('');
  lines.push('## Scope and boundary');
  lines.push('');
  lines.push(
    'All figures are **use-phase (operational) CO₂ only**: the energy consumed while using a product, multiplied by the emission factor of the energy carrier. Manufacturing, embodied carbon, and end-of-life are out of scope. The boundary is symmetric: **combustion-only factors for fuels** (no well-to-tank) and **generation-based grid intensity for electricity** (no upstream fuel supply). Gaseous fuel factors use the gross calorific value basis, which pairs consistently with US DOE appliance efficiencies (measured on the HHV basis) and with how gas is metered.',
  );
  lines.push('');
  lines.push('## Core factors');
  lines.push('');
  lines.push(`- Natural gas: **${FUEL_GCO2_PER_KWH_THERMAL.natural_gas} gCO₂/kWh** thermal, gross CV (DESNZ 2025, CO₂-only component)`);
  lines.push(`- LPG: **${FUEL_GCO2_PER_KWH_THERMAL.lpg} gCO₂/kWh** thermal, gross CV (DESNZ 2025)`);
  lines.push(`- Petrol: **${PETROL_KGCO2_PER_L} kgCO₂/L** (100% mineral, tailpipe, DESNZ 2025)`);
  lines.push(`- Diesel: **${DIESEL_KGCO2_PER_L} kgCO₂/L** (100% mineral, tailpipe, DESNZ 2025)`);
  lines.push('- Grid intensity: yearly gCO₂/kWh per country, Ember (latest year per country; see `country_factors.json`)');
  lines.push('- Water heating: 0.093 kWh useful per liter boiled from 20 °C (4.186 kJ/kg·K × 80 K)');
  lines.push('');
  lines.push('## Source registry');
  lines.push('');
  for (const s of [...sources].sort((a, b) => a.source_id.localeCompare(b.source_id))) {
    lines.push(`### ${s.source_id}`);
    lines.push('');
    lines.push(`${s.publisher} — *${s.title}* (${s.year}). License: ${s.license}. Retrieved ${s.retrieved_at}.`);
    lines.push(`<${s.url}>`);
    lines.push('');
  }
  lines.push('## Items');
  lines.push('');
  lines.push('| Item | Value | Year | Sources |');
  lines.push('|---|---|---|---|');
  for (const i of [...items].sort((a, b) => a.id.localeCompare(b.id))) {
    lines.push(`| ${i.emoji} ${i.name.en} (\`${i.id}\`) | ${itemValue(i)} | ${i.value_year} | ${i.source_ids.join(', ')} |`);
  }
  lines.push('');
  lines.push('## Verification status');
  lines.push('');
  const pending = items.filter((i) => i.assumption_note.en.includes('Pending'));
  lines.push(
    `${items.length - pending.length} of ${items.length} item values come from certified datasets, government conversion factors, regulated test data, or first-principles physics. The following ${pending.length} use documented product-class conventions and are flagged for verification against EPREL / measured datasets:`,
  );
  lines.push('');
  for (const i of pending) lines.push(`- \`${i.id}\` — ${i.assumption_note.en}`);
  lines.push('');
  return lines.join('\n');
}

const isMain = process.argv[1]?.endsWith('generate-sources-md.ts');
if (isMain) {
  const md = generateSourcesMd();
  const out = join(process.cwd(), 'data', 'SOURCES.md');
  writeFileSync(out, md);
  console.log(`wrote ${out} (${md.length} chars)`);
}
