/**
 * The technical appendix (spec §4.3.3), generated deterministically from the
 * source registry and items. The committed data/SOURCES.md is the English
 * edition; the About page renders it in the reader's language. Citation
 * titles, publishers and licenses stay in their original language.
 */
import { loadItems, loadSources } from './data';
import { DIESEL_KGCO2_PER_L, FUEL_GCO2_PER_KWH_THERMAL, PETROL_KGCO2_PER_L } from './constants';
import { L, plural, t, type StringKey } from './i18n';
import { formatExact, UNIT_SYMBOLS } from './format';
import type { Carrier, Item, Lang } from './types';

const carrierName = (c: Carrier, lang: Lang) => t(`carrier_${c}` as StringKey, lang);

function itemValue(i: Item, lang: Lang): string {
  const u = UNIT_SYMBOLS[lang];
  const n = (v: number) => formatExact(v, lang);
  switch (i.energy_model) {
    case 'power':
      return `${n(i.power_watts!)} ${u.W} (${carrierName(i.carrier, lang)})`;
    case 'per_event':
      return `${n(i.kwh_per_event!)} ${u.kWh}/${i.event_noun ? plural(i.event_noun[lang], 1, lang) : '1'}`;
    case 'task':
      return t('sm_val_task', lang, {
        useful: n(i.task_kwh_useful!),
        pct: Math.round((i.efficiency ?? 0) * 100),
        carrier: carrierName(i.carrier, lang),
      });
    case 'per_km':
      if (i.uses_country_car_default) return t('sm_val_country_car', lang);
      if (i.kwh_per_km != null) return `${n(i.kwh_per_km)} ${u.kWh}/${u.km}`;
      if (i.l_per_100km != null) return `${n(i.l_per_100km)} ${u.L}/100 ${u.km} (${carrierName(i.carrier, lang)})`;
      return `${n(i.gco2_per_km!)} ${u.g}CO₂/${u.km}`;
  }
}

export function generateSourcesMd(lang: Lang = 'en', { forFile = lang === 'en' } = {}): string {
  const sources = loadSources();
  const items = loadItems();
  const lines: string[] = [];
  lines.push(`# ${t('sm_title', lang)}`);
  lines.push('');
  if (forFile) {
    lines.push('_Generated by `scripts/generate-sources-md.ts` — do not edit by hand._');
    lines.push('');
  }
  lines.push(`## ${t('sm_scope_title', lang)}`);
  lines.push('');
  lines.push(t('sm_scope_p', lang));
  lines.push('');
  lines.push(`## ${t('sm_core_title', lang)}`);
  lines.push('');
  lines.push(`- ${t('sm_core_gas', lang, { v: formatExact(FUEL_GCO2_PER_KWH_THERMAL.natural_gas, lang) })}`);
  lines.push(`- ${t('sm_core_lpg', lang, { v: formatExact(FUEL_GCO2_PER_KWH_THERMAL.lpg, lang) })}`);
  lines.push(`- ${t('sm_core_petrol', lang, { v: formatExact(PETROL_KGCO2_PER_L, lang) })}`);
  lines.push(`- ${t('sm_core_diesel', lang, { v: formatExact(DIESEL_KGCO2_PER_L, lang) })}`);
  lines.push(`- ${t('sm_core_grid', lang)}`);
  lines.push(`- ${t('sm_core_water', lang, { v: formatExact(0.093, lang) })}`);
  lines.push('');
  lines.push(`## ${t('sm_registry_title', lang)}`);
  lines.push('');
  for (const s of [...sources].sort((a, b) => a.source_id.localeCompare(b.source_id))) {
    lines.push(`### ${s.source_id}`);
    lines.push('');
    lines.push(
      t('sm_registry_line', lang, {
        publisher: s.publisher,
        title: s.title,
        year: s.year,
        license: s.license,
        date: s.retrieved_at,
      }),
    );
    lines.push(`<${s.url}>`);
    lines.push('');
  }
  lines.push(`## ${t('sm_items_title', lang)}`);
  lines.push('');
  lines.push(
    `| ${t('sm_col_item', lang)} | ${t('sm_col_value', lang)} | ${t('about_col_year', lang)} | ${t('sm_col_sources', lang)} |`,
  );
  lines.push('|---|---|---|---|');
  for (const i of [...items].sort((a, b) => a.id.localeCompare(b.id))) {
    lines.push(`| ${i.emoji} ${L(i.name, lang)} (\`${i.id}\`) | ${itemValue(i, lang)} | ${i.value_year} | ${i.source_ids.join(', ')} |`);
  }
  lines.push('');
  lines.push(`## ${t('sm_verif_title', lang)}`);
  lines.push('');
  const pending = items.filter((i) => i.assumption_note.en.includes('Pending'));
  lines.push(t('sm_verif_p', lang, { ok: items.length - pending.length, total: items.length, pending: pending.length }));
  lines.push('');
  for (const i of pending) lines.push(`- \`${i.id}\` — ${L(i.assumption_note, lang)}`);
  lines.push('');
  return lines.join('\n');
}
